/*
 У вас есть массив чисел. 
 Напиши функцию countOccurrences, которая принимает массив чисел и
 возвращает объект с подсчётом каждого числа.
 const numbers = [1, 2, 2, 3, 4, 4, 4, 5];
 
 Ожидается: { 1: 1, 2: 2, 3: 1, 4: 3, 5: 1 }
*/

function countOccurrences(arr) {
  // Создаем пустой объект для хранения счетчиков
  const counts = {};

  // Перебираем каждый элемент в массиве
  for (const num of arr) {
    // Если ключ (число) уже существует, увеличиваем его счетчик
    // Если нет, создаем его и присваиваем значение 1
    counts[num] = (counts[num] || 0) + 1;
  }
  
  // Возвращаем итоговый объект
  return counts;
}

// Тестовые данные для проверки
const numbers = [1, 2, 2, 3, 4, 4, 4, 5];
const result = countOccurrences(numbers);

// Выводим результат в консоль, чтобы убедиться, что он правильный
console.log(result); // Ожидаем: { '1': 1, '2': 2, '3': 1, '4': 3, '5': 1 }

